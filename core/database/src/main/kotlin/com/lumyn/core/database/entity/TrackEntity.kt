package com.lumyn.core.database.entity

import androidx.room.Entity
import androidx.room.PrimaryKey
import com.lumyn.core.model.AudioSpec
import com.lumyn.core.model.Track

@Entity(tableName = "tracks")
data class TrackEntity(
    @PrimaryKey val id: Long,
    val contentUri: String,
    val title: String,
    val artist: String,
    val album: String,
    val albumArtist: String,
    val albumId: Long,
    val durationMs: Long,
    val trackNumber: Int,
    val discNumber: Int,
    val year: Int,
    val genre: String,
    val folderPath: String,
    val fileName: String,
    val mimeType: String,
    val codec: String,
    val bitDepth: Int,
    val sampleRateHz: Int,
    val bitrateKbps: Int,
    val channelCount: Int,
    val isLossless: Boolean,
    val artworkUri: String?,
    val isFavorite: Boolean,
    val dateAddedSeconds: Long,
    val replayGainTrackDb: Float? = null,
    val replayGainAlbumDb: Float? = null,
    val replayGainTrackPeak: Float? = null,
    val replayGainAlbumPeak: Float? = null,
    val clipStartMs: Long? = null,
    val clipEndMs: Long? = null,
    val cueSourcePath: String? = null,
    val playCount: Int = 0,
    val lastPlayedAtMs: Long = 0L,
    val totalPlayDurationMs: Long = 0L,
)

fun TrackEntity.toModel(): Track = Track(
    id = id,
    contentUri = contentUri,
    title = title,
    artist = artist,
    album = album,
    albumArtist = albumArtist,
    albumId = albumId,
    durationMs = durationMs,
    trackNumber = trackNumber,
    discNumber = discNumber,
    year = year,
    genre = genre,
    folderPath = folderPath,
    fileName = fileName,
    mimeType = mimeType,
    audioSpec = AudioSpec(codec, bitDepth, sampleRateHz, bitrateKbps, channelCount, isLossless),
    artworkUri = artworkUri,
    isFavorite = isFavorite,
    dateAddedSeconds = dateAddedSeconds,
    replayGainTrackDb = replayGainTrackDb,
    replayGainAlbumDb = replayGainAlbumDb,
    replayGainTrackPeak = replayGainTrackPeak,
    replayGainAlbumPeak = replayGainAlbumPeak,
    clipStartMs = clipStartMs,
    clipEndMs = clipEndMs,
    cueSourcePath = cueSourcePath,
    playCount = playCount,
    lastPlayedAtMs = lastPlayedAtMs,
    totalPlayDurationMs = totalPlayDurationMs,
)

fun Track.toEntity(): TrackEntity = TrackEntity(
    id = id,
    contentUri = contentUri,
    title = title,
    artist = artist,
    album = album,
    albumArtist = albumArtist,
    albumId = albumId,
    durationMs = durationMs,
    trackNumber = trackNumber,
    discNumber = discNumber,
    year = year,
    genre = genre,
    folderPath = folderPath,
    fileName = fileName,
    mimeType = mimeType,
    codec = audioSpec.codec,
    bitDepth = audioSpec.bitDepth,
    sampleRateHz = audioSpec.sampleRateHz,
    bitrateKbps = audioSpec.bitrateKbps,
    channelCount = audioSpec.channelCount,
    isLossless = audioSpec.isLossless,
    artworkUri = artworkUri,
    isFavorite = isFavorite,
    dateAddedSeconds = dateAddedSeconds,
    replayGainTrackDb = replayGainTrackDb,
    replayGainAlbumDb = replayGainAlbumDb,
    replayGainTrackPeak = replayGainTrackPeak,
    replayGainAlbumPeak = replayGainAlbumPeak,
    clipStartMs = clipStartMs,
    clipEndMs = clipEndMs,
    cueSourcePath = cueSourcePath,
    playCount = playCount,
    lastPlayedAtMs = lastPlayedAtMs,
    totalPlayDurationMs = totalPlayDurationMs,
)
